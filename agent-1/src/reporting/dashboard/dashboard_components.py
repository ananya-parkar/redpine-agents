def _col_widths(ws):
    spec = {
        "A":10,  "B":16, "C":12, "D":8,  "E":12,
        "F":12, "G":12, "H":18, "I":16, "J":12,
        "K":10, "L":18, "M":18, "N":12, "O":12,
        "P":12, "Q":14, "R":16, "S":14, "T":14,
    }
    for col, w in spec.items():
        ws.column_dimensions[col].width = w


