def _kpi_cards(ws, metrics):
    card_ranges = [
        ("A5:C8"),
        ("D5:F8"),
        ("G5:I8"),
        ("J5:L8"),
        ("M5:P8"),
    ]

    for row in range(5, 9):
        ws.row_dimensions[row].height = 20

    for idx, (metric_key, label, bg, fg) in enumerate(CARD_DEFS):
        rng = card_ranges[idx]
        ws.merge_cells(rng)

        value = metrics.get(metric_key, "—")

        delta = ""
        start_cell = rng.split(":")[0]
        c = ws[start_cell]
        c.value     = f"{label}\n\n{value}"
        c.font      = Font(bold=True, size=11, color=fg, name="Arial")
        c.fill      = _fill(bg)
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        c.border    = _border("D1D5DB")
        _apply(ws, rng, fill=_fill(bg), border=_border("D1D5DB"))

