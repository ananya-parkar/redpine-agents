def _add_lead_status_donut(ws, data_ws, df):
    chart = DoughnutChart()
    chart.holeSize = 55
    chart.firstSliceAng = 90
    chart.width = 10.5
    chart.height = 4
    chart.legend.position = "r"

    status_counts = (
        df["lead_status"]
        .fillna("NEW")
        .str.upper()
        .value_counts()
    )

    statuses = [
        "NEW",
        "PURSUING",
        "PASSED",
        "MONITORING",
        "UNDERWRITING"
    ]

    start_row = 201
    for idx, status in enumerate(statuses):
        data_ws.cell(start_row + idx, 1). value=status.title()
        data_ws.cell(start_row + idx, 2). value=status_counts.get(status, 0)

    labels = Reference(
        data_ws,
        min_col=1,
        min_row=201,
        max_row=205
    )

    data = Reference(
        data_ws,
        min_col=2,
        min_row=201,
        max_row=205
    )

    chart.add_data(data, titles_from_data=False)
    chart.set_categories(labels)

    chart.series[0].dLbls = _dLbls(show_val=False, show_pct=False)

    _color_series(chart.series[0], LEAD_STATUS_COLORS)
    ws.add_chart(chart, "A35")

def _bottom_section(ws, df, metrics, data_ws):
    br = 34

    # ── Lead Status Overview ──
    _section_title(ws, f"A{br}:F{br}", "Lead Status Overview")
    ws.row_dimensions[br].height = 18
    ws.merge_cells("F35:F41")
    ws["F35"] = ""

    _add_lead_status_donut(ws, data_ws, df)

    # ── Recent Activity ──
    _section_title(ws, f"G{br}:K{br}", "Recent Activity")
    activities = [
        ("🟢",
        f"{metrics['high_opportunity']} high-opportunity leads identified",
        "Current run"),
        ("🔴",
        f"{metrics['deep_distress']} distressed assets detected",
        "Distress scan"),
        ("🔵",
        f"{metrics['total_hotels']} hotels analyzed",
        "Market scan"),
        ("✅",
        "Dashboard generated",
        datetime.now().strftime("%I:%M %p"))
    ]

    for i, (icon, msg, ts) in enumerate(activities):
        r = br + 1 + i
        ws.row_dimensions[r].height = 18
        ws.cell(r, 7,  icon).font = Font(size=10, name="Arial")
        mc = ws.cell(r, 8, msg)
        mc.font = Font(size=9, color=TEXT_DARK, name="Arial")
        tc = ws.cell(r, 9, ts)
        tc.font = Font(size=9, color=TEXT_MED, italic=True, name="Arial")
    
    
    ws.merge_cells("J35:J41")
    ws["J35"] = ""

    ws.merge_cells("K35:K41")
    ws["K35"] = ""

    # - Run History -
    _section_title(ws, f"L{br}:P{br}", "Run History")
    headers=["Run Date", "Search Area", "Leads Found", "New Leads", "Duplicates"]

    run_data = [
        datetime.now().strftime("%b %d %Y"),
        metrics.get("search_area", ""),
        metrics.get("total_hotels", 0),
        metrics.get("high_opportunity", 0),
        0
    ]
    
    for idx, val in enumerate(run_data):
        c = ws.cell(row=br+2, column=12+idx, value=val)
        c.font = Font(size=8, color=TEXT_DARK, name="Arial")
        c.alignment = _align("center")
        c.border = _border()
    
    runs = get_recent_agent_runs(5)

    for idx, h in enumerate(headers):
        c = ws.cell(row=br+1, column=12+idx, value=h)
        c.font      = Font(bold=True, size=8, color=WHITE, name="Arial")
        c.fill      = _fill(GREEN_PRIMARY)
        c.alignment = _align("center")
        c.border    = _border("FFFFFF")
    
    for row_idx, run in enumerate(runs, start=br+2):
        values = [
            run[0].strftime("%b %d %Y"),
            run[1],
            run[2],
            run[3],
            run[4],
        ]

        for col_idx, value in enumerate(values):
            cell = ws.cell(
                row=row_idx,
                column=12 + col_idx,
                value=value
            )

            cell.font = Font(size=8)
            cell.alignment = _align("center")
            cell.border = _border()

            if row_idx % 2 == 0:
                cell.fill = _fill("F8FAFC")


def build_dashboard(ws, data_ws, metrics, df):
    _col_widths(ws)
    _header_and_run_history(ws, metrics, df)
    _kpi_cards(ws, metrics)
    _charts_section(ws, data_ws, df)
    ws.merge_cells("A20:P20")
    ws["A20"] = ""
    _top_opportunities_table(ws, df)
    ws.merge_cells("A33:P33")
    ws["A33"] = ""
    _bottom_section(ws, df, metrics, data_ws)
